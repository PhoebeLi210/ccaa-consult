# ==================== 便捷函数 ====================

def generate_emergency_plans(
    company_info: CompanyInfo,
    plan_types: List[str],
    include_summary: bool = True,
) -> List[GeneratedDocument]:
    """生成应急预案的便捷函数

    Args:
        company_info: 企业信息
        plan_types: 预案类型列表
        include_summary: 是否包含目录总册

    Returns:
        生成的文档列表
    """
    generator = DynamicEmergencyPlanGenerator(company_info, plan_types)
    documents = generator.generate()

    if include_summary and len(plan_types) > 1:
        summary = generator.generate_summary()
        documents.insert(0, summary)

    return documents


# ==================== 前端辅助函数 ====================

def get_emergency_plan_categories() -> List[Dict]:
    """获取应急预案分类列表（供前端使用）

    Returns:
        分类列表，每个分类包含code、name、plans字段
    """
    return [
        {"code": key, "name": value["name"], "plans": value["plans"]}
        for key, value in EMERGENCY_PLAN_CATEGORIES.items()
    ]


def get_all_plan_type_names() -> List[str]:
    """获取所有支持的预案类型名称

    Returns:
        预案类型名称列表（包含别名）
    """
    names = []
    for category in EMERGENCY_PLAN_CATEGORIES.values():
        names.extend(category["plans"])
    return names
