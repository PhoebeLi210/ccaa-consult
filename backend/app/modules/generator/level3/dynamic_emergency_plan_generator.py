class DynamicEmergencyPlanGenerator(BaseGenerator):
    """动态应急预案生成器

    根据用户选择的预案类型列表，动态生成对应的应急预案文档。
    """

    def __init__(self, company_info: CompanyInfo, plan_types: List[str]):
        """
        初始化

        Args:
            company_info: 企业信息
            plan_types: 预案类型列表，如 ["火灾", "触电", "高处坠落"]
        """
        super().__init__(company_info)
        self.plan_types = plan_types

    def _get_plan_template(self, plan_type: str) -> Dict:
        """获取预案模板

        先精确匹配，再别名匹配，最后返回通用模板。

        Args:
            plan_type: 预案类型名称

        Returns:
            预案模板字典
        """
        # 精确匹配
        if plan_type in EMERGENCY_PLAN_TEMPLATES:
            return EMERGENCY_PLAN_TEMPLATES[plan_type]

        # 别名匹配
        if plan_type in PLAN_TYPE_ALIASES:
            canonical = PLAN_TYPE_ALIASES[plan_type]
            if canonical in EMERGENCY_PLAN_TEMPLATES:
                return EMERGENCY_PLAN_TEMPLATES[canonical]

        # 模糊匹配
        for key, template in EMERGENCY_PLAN_TEMPLATES.items():
            if key in plan_type or plan_type in key:
                return template

        # 返回通用模板（以身体伤害作为通用预案）
        return EMERGENCY_PLAN_TEMPLATES["身体伤害"]

